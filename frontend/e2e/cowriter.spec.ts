import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

// Browser interaction fixtures only. Real authorization/persistence is covered by cowriter-api.test.ts.
test('co-writer popup keeps preview intact, reviews sources, shows proposals and protects unsaved edits', async ({ page }) => {
  const church = '10000000-0000-4000-8000-000000000001', prefix = `/api/v1/churches/${church}`;
  await page.goto('/api/v1/auth/login?persona=contributor');
  await page.waitForURL(url => !url.pathname.startsWith('/api/'));
  const session = await (await page.request.get('/api/v1/auth/session')).json();
  const workspace = await (await page.request.get(prefix + '/workspace')).json();
  const headers = { 'X-CSRF-Token': session.csrfToken, 'Idempotency-Key': randomUUID() };
  const slotResponse = await page.request.post(prefix + `/series/${workspace.series[0].id}/slots`, { headers, data: { localDate: '2026-12-07', localTime: '08:00', timeZone: 'America/New_York', assigneeIds: [session.user.id] } });
  expect(slotResponse.status()).toBe(201); const slot = await slotResponse.json();
  const plan = await (await page.request.get(prefix + '/plans/' + slot.planId)).json();
  const created = await page.request.post(prefix + `/plans/${plan.id}/content`, { headers: { ...headers, 'Idempotency-Key': randomUUID(), 'If-Match': plan.etag }, data: { mode: 'manual' } });
  expect(created.status()).toBe(201); const content = await created.json();
  // Persist a prior conversation/source through the real API, then restore it in the popup.
  const conversationPrefix=prefix+`/content/${content.id}/cowriter`;
  const prior=await page.request.post(conversationPrefix+'/conversations',{headers,data:{}});expect(prior.status()).toBe(201);const priorId=(await prior.json()).id;
  const priorSource=await page.request.post(conversationPrefix+'/sources',{headers,data:{conversationId:priorId,text:'John 6:68. Saved earlier sermon conversation.',confirmed:true,rightsConfirmed:true}});expect(priorSource.status()).toBe(200);
  let modelRequests = 0, confirmed = false;
  await page.route('**/cowriter/status', route => route.fulfill({ json: { configured: true, verified: false } }));
  await page.route('**/cowriter/sources', route => { confirmed = true; return route.fulfill({ json: { id: randomUUID(), reviewed: true } }); });
  await page.route('**/cowriter/messages', async route => {
    modelRequests++; const request = route.request().postDataJSON(); expect(confirmed).toBe(true);
    await route.fulfill({ json: { id: 'fixture-request', status: 'completed', error: null, result: { text: 'Fixture proposal, not a live model response.', usage: { inputTokens: 100, outputTokens: 50 }, proposal: { fields: [{ path: 'title', suggestion: 'Fixture proposed title', warnings: ['Human review required'], scriptureReferences: [] }] } } } });
    expect(request.kind).toBe('draft');
  });
  await page.route('**/cowriter/requests/fixture-request/adopt', route => route.fulfill({ json: { ...content, version: content.version + 1, headRevisionId: randomUUID(), head: { ...content.head, payload: { ...content.head.payload, title: 'Fixture proposed title' } } } }));
  await page.goto(`/studies?church=${church}&month=2026-12&slot=${slot.id}`);
  const preview = page.locator('.live-preview-panel');
  const previewBefore = await preview.textContent();
  await page.getByRole('button', { name: 'Open study co-writer' }).click();
  await expect(page.getByText('Configured · Ready to try', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Previous study conversations')).not.toBeVisible();
  await expect(page.getByRole('log',{name:'Co-writer conversation'})).toBeEmpty();
  await expect(page.getByRole('button',{name:/Read sermon transcript/})).not.toBeVisible();
  await page.screenshot({path:'frontend/test-results/cowriter-blank.png'});
  await page.getByRole('button',{name:'Co-writer menu',exact:true}).click();
  await page.getByLabel('Previous study conversations').selectOption(priorId);
  await expect(page.getByText('Conversation restored. Continue where you left off.',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Co-writer menu',exact:true}).click();
  await page.locator('.cowriter-source summary').click();
  await expect(page.getByLabel('Study document text')).toHaveValue('John 6:68. Saved earlier sermon conversation.');
  await page.locator('.cowriter-source summary').click();
  await page.getByRole('button',{name:'New conversation',exact:true}).click();
  const panel = page.getByRole('dialog', { name: 'Study co-writer' });
  const normalBounds = await panel.boundingBox();
  await page.getByRole('textbox', { name: 'Message the study co-writer' }).fill('Keep my unfinished question');
  await page.getByRole('button', { name: 'Expand study co-writer' }).click();
  const expandedBounds = await panel.boundingBox();
  expect(expandedBounds!.width).toBeGreaterThan(normalBounds!.width);
  expect(expandedBounds!.height).toBeGreaterThan(normalBounds!.height);
  await expect(page.getByRole('textbox', { name: 'Message the study co-writer' })).toHaveValue('Keep my unfinished question');
  await page.getByRole('button', { name: 'Restore co-writer size' }).click();
  expect((await panel.boundingBox())!.width).toBe(normalBounds!.width);
  await page.getByRole('button',{name:'Co-writer menu',exact:true}).click();
  await page.locator('.cowriter-source summary').click();
  await page.getByLabel('Study document text').fill('Synthetic sermon notes for the fixture.');
  await expect(page.getByRole('button', { name: 'Confirm document', exact: true })).toBeDisabled();
  await page.getByRole('checkbox', { name: /I reviewed this text/ }).check();
  await page.getByRole('button', { name: 'Confirm document', exact: true }).click();
  await page.getByRole('button',{name:'Co-writer menu',exact:true}).click();
  await expect(page.getByRole('button', { name: 'Document confirmed', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Write today’s study/ }).click();
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  const adopt = page.getByRole('button', { name: 'Adopt proposal into saved draft' }); await expect(adopt).toBeVisible();
  expect(modelRequests).toBe(1); expect(await preview.textContent()).toBe(previewBefore);
  await adopt.click(); await expect(page.getByTestId('content-title')).toHaveValue('Fixture proposed title');
  await page.getByTestId('content-title').fill('My unsaved title');
  await page.getByRole('textbox', { name: 'Message the study co-writer' }).fill('Another question');
  await expect(page.getByRole('button', { name: 'Send message', exact: true })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  const bounds = await page.getByRole('dialog', { name: 'Study co-writer' }).boundingBox(); expect(bounds!.x).toBeGreaterThanOrEqual(0); expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Expand study co-writer' }).click();
  const mobileExpanded = await panel.boundingBox();
  expect(mobileExpanded!.height).toBeGreaterThan(bounds!.height);
  expect(mobileExpanded!.x + mobileExpanded!.width).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Close study co-writer' }).click(); await expect(page.getByRole('button', { name: 'Open study co-writer' })).toBeVisible();
});
